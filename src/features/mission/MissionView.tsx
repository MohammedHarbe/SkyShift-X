/** Mission, methodology, integrity rules and sources. Everything citable is fetched from the API. */
import type { ReactNode } from 'react';
import { Link } from 'react-router';
import { useHealth, useSources } from '@/api';
import { config } from '@/config/env';
import type { EpistemicStatus } from '@/contracts/v1';
import { Badge, ClassificationBadge, EpistemicBadge, ExternalLink, Panel, QueryBoundary } from '@/ui';

const STATUSES: { status: EpistemicStatus; meaning: string }[] = [
  { status: 'established', meaning: 'Accepted science, with a source where one is cited.' },
  { status: 'observed', meaning: 'A real measurement from real data.' },
  { status: 'model-derived', meaning: 'The output of a model or processing pipeline.' },
  { status: 'hypothesis', meaning: 'Proposed but not confirmed. Planet Nine is in this category.' },
  { status: 'illustrative', meaning: 'A teaching visual. Not data.' },
  { status: 'simulated', meaning: 'Synthetic data made to test the tool. Not a real measurement.' },
];

function Section({ id, eyebrow, title, children }: { id: string; eyebrow: string; title: string; children: ReactNode }) {
  return (
    <section aria-labelledby={id} className="scroll-mt-20">
      <div className="eyebrow text-cyan">{eyebrow}</div>
      <h2 id={id} className="display mt-1 text-2xl text-ice sm:text-3xl">
        {title}
      </h2>
      <div className="mt-4 space-y-3 text-[15px] leading-relaxed text-mist">{children}</div>
    </section>
  );
}

export default function MissionView() {
  const sources = useSources();
  const health = useHealth();
  const caps = health.data?.data.capabilities;

  return (
    <div className="pointer-events-auto scroll-area h-full bg-gradient-to-b from-ink to-void">
      <div className="mx-auto max-w-4xl space-y-12 px-5 py-10 sm:px-8 sm:py-14">
        <header>
          <p className="eyebrow">Mission, method and sources</p>
          <h1 className="display mt-2 text-4xl text-ice sm:text-5xl">How SkyShift X works, and what it does not claim</h1>
        </header>

        <Section id="challenge" eyebrow="The challenge" title="Make it easy for anyone to see the sky change">
          <p>
            SkyShift X is an entry for the NASA Space Apps Challenge 2026, <em>Planet X and SPHEREx</em>. The challenge asks for a public-facing web tool that displays SPHEREx sky images and makes it easy for anyone to see how they change over time.
          </p>
          <p>
            The <Link to="/time" className="text-cyan underline decoration-cyan/40 underline-offset-2">Time Explorer</Link> is the direct answer: pick a patch of sky, pick two dates, then blink or subtract the images. The <Link to="/explore" className="text-cyan underline decoration-cyan/40 underline-offset-2">3D explorer</Link> gives the context for why movement matters in the outer solar system, and <Link to="/journey/journey-moving-source" className="text-cyan underline decoration-cyan/40 underline-offset-2">Discovery Journeys</Link> explain what a change does and does not mean.
          </p>
        </Section>

        <Section id="status" eyebrow="Current status" title="What is real in this build">
          <Panel className="text-sm">
            <dl className="grid gap-x-6 gap-y-3 sm:grid-cols-[auto_1fr]">
              <dt className="text-dim">Data mode</dt>
              <dd className="text-ice">
                {config.apiMode === 'mock' ? (
                  <>
                    <Badge tone="amber">Demo</Badge> In-app mock data service. Nothing is fetched from NASA.
                  </>
                ) : (
                  <>
                    <Badge tone="cyan">Live</Badge> Connected to <span className="num">{config.apiBaseUrl}</span>
                  </>
                )}
              </dd>
              <dt className="text-dim">Sky images and difference images</dt>
              <dd className="text-ice">
                {caps?.liveObservations ? 'Supplied by the data service from SPHEREx products.' : 'Simulated. Synthetic star fields shaped like SPHEREx cutouts, with a few changing sources injected on purpose.'}
              </dd>
              <dt className="text-dim">Candidates, measurements, spectra</dt>
              <dd className="text-ice">{caps?.liveObservations ? 'Supplied by the data service.' : 'Simulated, and labelled wherever they appear.'}</dd>
              <dt className="text-dim">Discovery Journeys</dt>
              <dd className="text-ice">
                {caps?.dynamicJourneys ? 'Generated by the AI service from the selected evidence.' : 'One prepared journey, written by the team. Questions it cannot answer are declined; no AI model is running in this build.'}
              </dd>
              <dt className="text-dim">3D solar system</dt>
              <dd className="text-ice">A visualisation: real, rounded orbital elements for confirmed bodies; compressed distances, exaggerated sizes, illustrative positions.</dd>
            </dl>
          </Panel>
          <p>
            Real SPHEREx data arrives through a separate scientific backend built by the team. The website talks to it through a documented, versioned API. If that service fails, SkyShift X shows an error. It never swaps in simulated data silently.
          </p>
        </Section>

        <Section id="method" eyebrow="Method" title="From SPHEREx exposures to a careful question">
          <ol className="list-decimal space-y-2 pl-5">
            <li>
              <span className="text-ice">Repeated coverage.</span> SPHEREx surveys the whole sky at 0.75–5.0 µm in six detector bands. Each exposure sees a given position at one wavelength, and the same position is imaged again on many later dates.
            </li>
            <li>
              <span className="text-ice">Aligned epochs.</span> The backend retrieves image cutouts of one region from different dates and puts them on a common pixel grid.
            </li>
            <li>
              <span className="text-ice">Difference images.</span> Subtracting an earlier image from a later one cancels everything that stayed the same. What is left changed.
            </li>
            <li>
              <span className="text-ice">Candidates.</span> The backend lists sources that changed and measures them. The website performs no detection of its own.
            </li>
            <li>
              <span className="text-ice">Explanations before conclusions.</span> Every candidate is shown with the ordinary explanations first: known asteroids, variable stars, detector artifacts, misalignment. Assessments are qualitative; no probabilities are invented.
            </li>
          </ol>
        </Section>

        <Section id="integrity" eyebrow="Scientific integrity" title="How to read the labels">
          <ul className="grid gap-2.5 sm:grid-cols-2">
            {STATUSES.map((s) => (
              <li key={s.status} className="flex items-start gap-3 rounded-xl border border-line bg-black/25 p-3 text-sm">
                <EpistemicBadge status={s.status} className="mt-0.5 shrink-0" />
                <span>{s.meaning}</span>
              </li>
            ))}
          </ul>
          <ul className="list-disc space-y-1.5 pl-5">
            <li>
              <span className="text-ice">Planet Nine is a hypothesis.</span> No such planet has been observed. SkyShift X draws no orbit for it and reports no detection.
            </li>
            <li>A moving source is not assumed to be a planet. Most movers in survey images are known asteroids.</li>
            <li>Every image and chart carries a label saying whether it is a real observation, simulated, or an illustration.</li>
          </ul>
        </Section>

        <Section id="assets" eyebrow="Imagery" title="Asset manifest">
          <p>This build contains no third-party imagery. Everything on screen is one of:</p>
          <ul className="space-y-2">
            <li className="flex flex-wrap items-center gap-2">
              <ClassificationBadge classification="procedural-visualization" /> The 3D solar system, drawn in the browser from shapes and shaders.
            </li>
            <li className="flex flex-wrap items-center gap-2">
              <ClassificationBadge classification="simulated" /> Sky images, difference images and spectra, generated by the project’s simulator.
            </li>
            <li className="flex flex-wrap items-center gap-2">
              <ClassificationBadge classification="illustrative-diagram" /> Teaching diagrams, drawn for SkyShift X.
            </li>
          </ul>
          <p>
            When real images are added, each one is recorded with its source link, credit, usage terms, classification and observation details, and shown with that credit.
          </p>
        </Section>

        <Section id="sources" eyebrow="References" title="Scientific sources">
          <QueryBoundary query={sources} loadingLabel="Loading sources…">
            {(list) => (
              <ul className="space-y-3">
                {list.map((s) => (
                  <li key={s.id} className="rounded-xl border border-line bg-black/25 p-4 text-sm">
                    <div className="flex flex-wrap items-center gap-2">
                      <Badge>{s.kind.replace('-', ' ')}</Badge>
                      <ExternalLink href={s.url} className="font-medium">
                        {s.title}
                      </ExternalLink>
                    </div>
                    <p className="mt-1 text-dim">{[s.authors, s.publisher, s.year].filter(Boolean).join(' · ')}</p>
                    {s.note && <p className="mt-1 text-mist">{s.note}</p>}
                  </li>
                ))}
              </ul>
            )}
          </QueryBoundary>
          <p className="text-sm">
            Publications that use SPHEREx data products are asked by IRSA to include this acknowledgement: “This publication makes use of data products from the Spectro-Photometer for the History of the Universe, Epoch of Reionization and Ices Explorer (SPHEREx), which is a joint project of the Jet Propulsion Laboratory and the California Institute of Technology, and is funded by the National Aeronautics and Space Administration.”
          </p>
        </Section>

        <Section id="access" eyebrow="Accessibility" title="Built to work without sound, motion or 3D">
          <ul className="list-disc space-y-1.5 pl-5">
            <li>Journeys always show captions and a full transcript, and play without audio if no voice is available.</li>
            <li>With reduced motion turned on in your system, camera flights become cuts and blink comparison is manual.</li>
            <li>If 3D graphics are unavailable, the explorer falls back to a flat diagram with the same information.</li>
            <li>All controls can be reached and operated from the keyboard.</li>
          </ul>
        </Section>
      </div>
    </div>
  );
}
